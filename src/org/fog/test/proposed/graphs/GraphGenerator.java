    private static void printBanner(String title, String dir, String tag) {
        System.out.println();
        System.out.println("  -------------------------------------------------------------");
        System.out.printf ("    %s [%s]%n", title, tag);
        System.out.printf ("    -> %s%n", dir);
        System.out.println("  -------------------------------------------------------------");
    }

    private static void printSuccess(String dir, String[] figures) {
        System.out.println("  [OK] All figures saved -> " + dir);
        for (String f : figures) {
            System.out.println("     [OK]  " + f);
        }
        System.out.println("  Location: " + dir);
    }

